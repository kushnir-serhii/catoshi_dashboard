#!/usr/bin/env node
// Writes context/components-index.md — a compact map of reusable components
// (path, name, props, one-line purpose) so planning/implementation agents reuse
// instead of re-creating. Zero model cost; run it any time.
import fs from 'node:fs';
import path from 'node:path';
import { findComponents, walk, rel, defaultComponentDirs, loadConfig, ROUTE_FILE } from './lib-components.mjs';

const root = process.env.CLAUDE_PROJECT_DIR || process.cwd();
const cfg = loadConfig(root);
const dirs = cfg.componentDirs?.length ? cfg.componentDirs : defaultComponentDirs(root);
const outFile = path.join(root, cfg.componentIndexPath || 'context/components-index.md');

function propsOf(src, name, declLine) {
  // 1) interface/type NameProps { a: ...; b?: ... }
  const re = new RegExp(`(?:interface\\s+${name}Props\\b[^{]*|type\\s+${name}Props\\s*=\\s*)\\{([\\s\\S]*?)\\n\\}`);
  const m = src.match(re);
  let body = m?.[1];
  if (!body) {
    // 2) destructured params on the declaration line(s): Name({ a, b = 1, ...rest }
    const chunk = src.split(/\r?\n/).slice(declLine - 1, declLine + 6).join(' ');
    const d = chunk.match(/\(\s*\{([^}]*)\}/);
    if (d) return d[1].split(',').map(s => s.trim().split(/[=:\s]/)[0]).filter(s => s && !s.startsWith('...')).slice(0, 10);
    return [];
  }
  return [...body.matchAll(/^\s*(?:readonly\s+)?([A-Za-z_$][\w$]*)\??\s*:/gm)].map(x => x[1]).slice(0, 10);
}

const clean = t => t.replace(/[─━═\-=*#]{3,}/g, ' ').replace(/\s+/g, ' ').trim();

function purposeOf(src, declLine) {
  const lines = src.split(/\r?\n/);
  let i = declLine - 2;
  while (i >= 0 && lines[i].trim() === '') i--;
  if (i < 0) return '';
  const l = lines[i].trim();
  if (l.startsWith('//')) return clean(l.replace(/^\/\/\s*/, ''));
  if (l.endsWith('*/')) {
    let j = i;
    while (j > 0 && !lines[j].includes('/**') && !lines[j].includes('/*')) j--;
    const text = lines.slice(j, i + 1).join(' ').replace(/\/\*\*?|\*\/|\s\*\s?/g, ' ').replace(/\s+/g, ' ').trim();
    return clean(text).split(/(?<=\.)\s/)[0].slice(0, 120);
  }
  return '';
}

const groups = new Map();
let total = 0, multi = [];
for (const d of dirs) {
  for (const file of walk(path.join(root, d))) {
    if (ROUTE_FILE.test(path.basename(file)) || /\.(test|spec|stories)\./.test(file)) continue;
    const src = fs.readFileSync(file, 'utf8');
    const comps = findComponents(src);
    if (!comps.length) continue;
    const r = rel(root, file);
    if (comps.length > 1) multi.push(`${r} (${comps.length})`);
    const g = path.posix.dirname(r);
    if (!groups.has(g)) groups.set(g, []);
    for (const c of comps) {
      total++;
      const props = propsOf(src, c.name, c.line);
      const why = purposeOf(src, c.line);
      groups.get(g).push(`- \`${c.name}\` ${path.posix.basename(r)}${props.length ? ` · props: ${props.join(', ')}` : ''}${why ? ` · ${why}` : ''}`);
    }
  }
}

let md = `# Components index\n\n_Auto-generated by \`node .awos-tune/scripts/component-index.mjs\` — do not edit. ${total} components. Check here before creating a new one; prefer \`extend\` (new prop/variant) over a near-duplicate._\n`;
for (const [g, items] of [...groups].sort()) md += `\n## ${g}\n${items.join('\n')}\n`;
if (multi.length) md += `\n## ⚠ Multi-component files (split when touched)\n${multi.map(m => `- ${m}`).join('\n')}\n`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, md);
console.log(`components-index: ${total} components in ${groups.size} folders → ${rel(root, outFile)}`);
